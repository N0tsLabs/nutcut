function translateToken(token) {
  if (/[\u4e00-\u9fa5]/.test(token)) return token
  const lower = token.toLowerCase()
  if (/^\d+$/.test(token)) return token
  if (WORDS[lower]) return WORDS[lower]
  const family = /^([a-z]+?)(\d+)$/.exec(lower)
  if (family && FAMILY[family[1]]) return `${FAMILY[family[1]]}${family[2]}`
  if (SKIP.has(lower)) return ''
  return ''
}

export function translatePart(part) {
  let cleaned = String(part || '')
  for (const [en, zh] of Object.entries(PHRASES).sort((a, b) => b[0].length - a[0].length)) {
    cleaned = cleaned.replace(new RegExp(`\\b${en.replace(/\s+/g, '\\s+')}\\b`, 'gi'), ` ${zh} `)
  }
  cleaned = cleaned.replace(/\bFS(\d+)\b/gi, '音效$1').replace(/[()]/g, ' ')
  const tokens = cleaned.split(/\s+/).filter(Boolean)
  const out = []
  for (const token of tokens) {
    const translated = translateToken(token)
    if (translated) out.push(translated)
  }
  return out.join('')
}

export function translateTitle(title, category = '') {
  const parts = String(title || '').split(/\s+·\s+/)
  const translated = parts.map(translatePart).filter(Boolean)
  if (!translated.length) return `${CATEGORY_ZH[category] || '音效'}音效`
  return translated.join(' · ')
}

export function translateTags(tags = [], category = '') {
  const out = new Set()
  if (CATEGORY_ZH[category]) out.add(CATEGORY_ZH[category])
  for (const tag of tags) {
    const translated = translatePart(tag)
    if (translated) out.add(translated)
  }
  return [...out].slice(0, 8)
}

export function localizeTrack(track) {
  const categoryZh = CATEGORY_ZH[track.category] || '音效'
  return {
    ...track,
    titleEn: track.titleEn || track.title,
    titleZh: track.titleZh || translateTitle(track.title, track.category),
    tagsZh: track.tagsZh || translateTags(track.tags, track.category),
    categoryZh,
  }
}

